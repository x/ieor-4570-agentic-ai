# Every entity: name -> (column, values). One map, two kinds of entity.
TERMS = {name: ("incident_zip", zips) for name, zips in NEIGHBORHOODS.items()}
TERMS |= {name: ("agency", [code]) for name, code in AGENCIES.items()}
_BY_LOWER = {name.lower(): name for name in TERMS}
_LONGEST = max(len(name.split()) for name in TERMS)


def expand(question: str) -> str:
    """Append what each entity named in the question means in the database."""
    # If the user already gave ZIP codes, trust them over the neighborhood map.
    has_zips = re.search(r"\b1\d{4}\b", question) is not None
    words = re.findall(r"[a-z'.-]+", question.lower())
    found, meanings = [], set()
    # Try every phrase, longest first. 0.85 similarity forgives a typo ("park slop") but not a different name.
    for n in range(_LONGEST, 0, -1):
        for i in range(len(words) - n + 1):
            match = get_close_matches(" ".join(words[i : i + n]), _BY_LOWER, n=1, cutoff=0.85)
            if not match:
                continue
            name = _BY_LOWER[match[0]]
            column, values = TERMS[name]
            if (column == "incident_zip" and has_zips) or (column, tuple(values)) in meanings:
                continue
            meanings.add((column, tuple(values)))
            found.append(f"{name} is {column} {', '.join(values)}.")
    return question + "\n\n" + " ".join(found) if found else question


